"""Rebuild the reviewed legacy UI bridge after flutter gen-l10n.

ARB files remain the source of translations. The frozen audit supplies aliases
for the original UI wording; additional short labels live in supplemental_ui.json.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
L10N = ROOT / 'lib/l10n'
arb = json.loads((L10N / 'app_id.arb').read_text(encoding='utf-8'))
generated = (L10N / 'generated/app_localizations.dart').read_text(encoding='utf-8')
aliases = json.loads((L10N / 'legacy_ui_aliases.json').read_text(encoding='utf-8'))
english_aliases = json.loads((L10N / 'english_ui_aliases.json').read_text(encoding='utf-8'))

def quote(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')

exact, patterns = [], []
seen_exact = set()
seen_sources = set()
for key, value, reverse in [(k,v,False) for k,v in arb.items()] + [(k,v,True) for k,v in english_aliases.items()]:
    if key.startswith('@') or not isinstance(value, str) or key == 'signInAction' or key.startswith('relative'):
        continue
    source = value if reverse else aliases.get(key, value)
    source = re.sub(r'\{\{(par\d+)\}\}', r'{\1}', source)
    source = source.replace('${e.message}', '{message}').replace('$message', '{message}')
    if source in seen_sources:
        continue
    seen_sources.add(source)
    captures = list(re.finditer(r'\{(\w+)\}', source))
    method = re.search(r'  String '+re.escape(key)+r'\((.*?)\);', generated, re.S)
    if not captures or method is None:
        if source in seen_exact:
            continue
        seen_exact.add(source)
        exact.append(f'  {quote(source)}: (l) => l.{key},')
        continue
    params = re.findall(r'String (\w+)', method.group(1))
    names = [m.group(1) for m in captures]
    pattern, last = '^', 0
    for match in captures:
        pattern += re.escape(source[last:match.start()]) + '(.*?)'
        last = match.end()
    pattern += re.escape(source[last:]) + '$'
    args = ', '.join(f'v[{names.index(p)}]' for p in params)
    literals = [p for p in re.split(r'\{\w+\}', source) if p.strip()]
    anchor = max(literals, key=len, default='')
    patterns.append((len(source)-sum(len(m.group()) for m in captures), f'  _PosPattern({quote(pattern)}, {quote(anchor)}, (l, v) => l.{key}({args})), '))
patterns.sort(key=lambda p: -p[0])
result = '''// Generated by scripts/build_pos_translation_lookup.py. UI copy only.
import 'generated/app_localizations.dart';
typedef _PosValue = String Function(AppLocalizations);
class _PosPattern {
  _PosPattern(String source, this.anchor, this.render) : pattern = RegExp(source, dotAll: true);
  final RegExp pattern;
  final String anchor;
  final String Function(AppLocalizations, List<String>) render;
}
final Map<String, _PosValue> _exact = {
'''+ '\n'.join(exact)+ '\n};\nfinal List<_PosPattern> _patterns = [\n'+ '\n'.join(p[1] for p in patterns)+'''
];
final Map<(String, String), String> _cache = {};
String translatePosText(String source, AppLocalizations locale) {
  final key = (locale.localeName, source);
  final cached = _cache[key];
  if (cached != null) return cached;
  final result = _translate(source, locale);
  if (_cache.length >= 1024) _cache.clear();
  _cache[key] = result;
  return result;
}
String _translate(String source, AppLocalizations locale) {
  final exact = _exact[source];
  if (exact != null) return exact(locale);
  for (final entry in _patterns) {
    if (entry.anchor.isNotEmpty && !source.contains(entry.anchor)) continue;
    final match = entry.pattern.firstMatch(source);
    if (match != null) {
      return entry.render(locale, [for (var i=1;i<=match.groupCount;i++) match.group(i) ?? '']);
    }
  }
  return source;
}
'''
(L10N / 'pos_translation_lookup.dart').write_text(result, encoding='utf-8')
print(f'{len(exact)} exact UI labels; {len(patterns)} parameterized UI templates.')
